export function resolveOverviewError(stage: 'login' | 'collection' | 'ingestion' | 'validation', errorCode: string, detail?: string) {
  const entry = stage === 'ingestion'
    ? (ingestionErrorCodes[errorCode] ? [ingestionErrorCodes[errorCode], ingestionErrorCodes[errorCode]] : undefined)
    : stage === 'validation' ? undefined : collectionErrorCodes[errorCode];
  return {
    errorCode,
    issueType: entry?.[0] ?? `错误码 ${errorCode}`,
    reason: detail?.trim() || entry?.[1] || '--',
  };
}
